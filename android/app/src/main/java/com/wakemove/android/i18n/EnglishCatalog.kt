package com.wakemove.android.i18n

/** English copy for every user-facing Chinese phrase in the app. */
internal object EnglishCatalog {
    fun translate(chinese: String): String = exact[chinese] ?: translateDynamic(chinese) ?: chinese

    private fun translateDynamic(text: String): String? = when {
        text.startsWith("WakeMove · 醒动  v") -> text.replace("WakeMove · 醒动", "WakeMove")
        text.matches(Regex("^WakeMove v.+ 可以更新$")) -> text.replace(" 可以更新", " is available")
        text.matches(Regex("^WakeMove v.+ 已经准备好$")) -> text.replace(" 已经准备好", " is ready")
        text.startsWith("已忽略 WakeMove v") -> text.replace("已忽略", "Ignored")
        text.startsWith("当前是最新版本 v") -> text.replace("当前是最新版本", "Up to date")
        text.startsWith("你正在使用 WakeMove v") -> text.replace("你正在使用", "You are using").replace("。", ".")
        text.startsWith("正在下载 WakeMove v") -> text.replace("正在下载", "Downloading")
        text.startsWith("版本服务暂时不可用（") -> text
            .replace("版本服务暂时不可用（", "Version service unavailable (")
            .replace("）", ")")
        text.startsWith("下载服务返回 ") -> text.replace("下载服务返回", "Download server returned")
        text.matches(Regex("^正在下载，已完成 \\d+%$")) -> text.replace("正在下载，已完成", "Downloading —")
        text.matches(Regex("^已下载 \\d+%$")) -> text.replace("已下载", "Downloaded")
        text.matches(Regex("^\\d+ 个$")) -> text.replace(" 个", " alarms")
        text.matches(Regex("^\\d+ 次$")) -> text.replace(" 次", " reps")
        text.startsWith("目标：") -> text.replaceFirst("目标：", "Goal: ")
        text.startsWith("进度：") -> text.replaceFirst("进度：", "Progress: ")
        text.startsWith("听到：") -> text.replaceFirst("听到：", "Heard: ")
        text.startsWith("剩余贪睡 ") -> text.replace("剩余贪睡", "Snoozes left").replace(" 次", "")
        text.startsWith("贪睡一次（还剩 ") -> text
            .replace("贪睡一次（还剩 ", "Snooze (")
            .replace(" 次）", " left)")
        text.startsWith("完成目标 ") -> text.replace("完成目标", "Complete").replace("，闹钟才会停止", " to stop the alarm")
        text.startsWith("倒计时 ") -> text.replace("倒计时", "Countdown:").replace(" 秒，激活可取消", "s; activate again to cancel")
        text.startsWith("约 ") && text.endsWith(" 分钟后") -> text.replace("约 ", "In about ").replace(" 分钟后", " min")
        text.startsWith("约 ") && text.endsWith(" 小时后") -> text.replace("约 ", "In about ").replace(" 小时后", " hr")
        text.startsWith("闹钟时间 ") -> text.replace("闹钟时间", "Alarm time")
        text.startsWith("下一次响铃：") -> text
            .replace("下一次响铃：", "Next alarm: ")
            .replace("（", " (")
            .replace("）", ")")
        text.startsWith("最近调度：") -> text.replace("最近调度：", "Last schedule: ")
        text.startsWith("下次已注册：") -> text.replace("下次已注册：", "Next registered: ")
        text.startsWith("实际响铃：") -> text.replace("实际响铃：", "Rang at: ")
        text.startsWith("完成时间：") -> text.replace("完成时间：", "Completed at: ")
        text.startsWith("最近投递：") -> text.replace("最近投递：", "Last delivery: ")
        text.startsWith("失败位置：") -> text.replace("失败位置：", "Failed at: ")
        text.startsWith("修复") -> text.replaceFirst("修复", "Fix ")
        text.startsWith("请在系统设置开启") -> text
            .replace("请在系统设置开启", "Enable ")
            .replace("权限", " permission in system settings")
        text.endsWith("权限被拒绝，可再次请求或改用备用挑战") -> text
            .replace("权限被拒绝，可再次请求或改用备用挑战", " permission was denied. Try again or use the fallback challenge.")
        text.startsWith("备用目标：") -> text.replace("备用目标：", "Fallback goal: ")
        text.contains(" · 贪睡 ") && text.endsWith(" 次") -> text.replace(" · 贪睡 ", " · Snoozed ").replace(" 次", " times")
        text.startsWith("贪睡中 · ") -> text.replace("贪睡中 · ", "Snoozed · ").replace(" 再响", " rings again")
        text.startsWith("试听") -> text.replaceFirst("试听", "Preview ")
        text.startsWith("停止试听") -> text.replaceFirst("停止试听", "Stop previewing ")
        text.endsWith(" 次") -> text.removeSuffix(" 次") + " reps"
        else -> null
    }

